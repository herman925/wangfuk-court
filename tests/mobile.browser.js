// Run this expression in the loaded site's browser at a width of 650px or less.
(async () => {
  const el = id => document.getElementById(id);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const tick = () => new Promise(resolve => setTimeout(resolve, 50));
  const snapshot = await (await fetch('./data/snapshot.json', { cache: 'no-cache' })).json();
  const kai = snapshot.estates.find(e => e.name === '啟陽苑');
  check(innerWidth <= 650, 'Use a mobile viewport');
  const opener = el('open-filters'), drawer = el('filter-drawer');
  check(!drawer.open, 'Filters should start closed on mobile');
  opener.focus(); opener.click();
  check(drawer.matches(':modal'), 'Drawer should isolate the background');
  check(drawer.contains(document.activeElement), 'Focus should move into drawer');
  el('query').focus();
  check(drawer.contains(document.activeElement), 'Background must not take focus');
  el('estate').value = '啟陽苑';
  el('estate').dispatchEvent(new Event('change'));
  check(el('apply-filters').textContent.includes(String(kai.initial)), 'Full estate count should update');
  el('apply-filters').click(); await tick();
  check(!drawer.open && !document.body.classList.contains('drawer-open'), 'Apply must close and unlock');
  check(document.activeElement === opener, 'Focus should return to trigger');
  check(el('result-count').textContent.includes(`${kai.initial.toLocaleString('zh-HK')} 伙`), 'Closing must retain filters');
  opener.click();
  el('status').value = 'available'; el('status').dispatchEvent(new Event('change'));
  check(el('result-count').textContent.includes(`${kai.available.toLocaleString('zh-HK')} 伙`), 'Available-only filter');
  el('status').value = 'picked'; el('status').dispatchEvent(new Event('change'));
  check(el('result-count').textContent.includes(`${kai.picked.toLocaleString('zh-HK')} 伙`), 'Picked-only filter');
  check(document.querySelectorAll('#flat-rows .picked').length > 0, 'Picked rows must have red status class');
  el('minArea').value = '900'; el('minArea').dispatchEvent(new Event('input'));
  check(el('apply-filters').textContent.includes('0'), 'Empty results should update count');
  el('reset').click();
  check(el('result-count').textContent.includes(`${snapshot.initialCount.toLocaleString('zh-HK')} 伙`), 'Reset should restore entire special-exercise inventory');
  el('close-filters').click(); await tick();
  check(!drawer.open && opener.getAttribute('aria-expanded') === 'false', 'Close must reset trigger state');
  const savedOpener = el('open-wishlist-mobile'), savedDrawer = el('wishlist-drawer');
  const leftButton = savedOpener.getBoundingClientRect(), rightButton = opener.getBoundingClientRect();
  check(leftButton.right <= rightButton.left, 'Bottom buttons must not overlap');
  savedOpener.focus(); savedOpener.click();
  check(savedDrawer.matches(':modal'), 'Wishlist drawer must be modal');
  check(savedDrawer.contains(document.activeElement), 'Wishlist must receive focus');
  el('query').focus();
  check(savedDrawer.contains(document.activeElement), 'Wishlist must isolate background focus');
  check(document.querySelectorAll('dialog:modal').length === 1, 'Only one drawer may be modal');
  el('close-wishlist').click(); await tick();
  check(!savedDrawer.open && !document.body.classList.contains('drawer-open'), 'Wishlist must close and unlock');
  check(document.activeElement === savedOpener, 'Wishlist focus must return to its trigger');
  check(savedOpener.getAttribute('aria-expanded') === 'false', 'Wishlist trigger must reset');
  check(document.documentElement.scrollWidth <= innerWidth, 'Mobile page must not overflow horizontally');
  check(document.querySelector('table').scrollWidth <= innerWidth, 'Mobile flats must fit viewport');
  return 'Both mobile drawers, focus isolation/return, filtering, empty state, reset and layout passed';
})()
